/// Draw `text` at (x, y) with pixel scale `s` onto an RGB buffer, with a dark backing box.
pub fn draw(img: &mut image::RgbImage, x: u32, y: u32, s: u32, text: &str) {
    let w = (text.chars().count() as u32 * 6 + 1) * s;
    let h = 9 * s;
    for yy in y..(y + h).min(img.height()) {
        for xx in x..(x + w).min(img.width()) {
            let p = img.get_pixel_mut(xx, yy);
            for c in 0..3 {
                p.0[c] = (p.0[c] as u32 * 35 / 100) as u8;
            }
        }
    }
    for (i, ch) in text.chars().enumerate() {
        let ch = ch.to_ascii_uppercase();
        let Some((_, g)) = GLYPHS.iter().find(|(c, _)| *c == ch) else { continue };
        for (r, row) in g.iter().enumerate() {
            for (c, b) in row.bytes().enumerate() {
                if b != b'#' {
                    continue;
                }
                for dy in 0..s {
                    for dx in 0..s {
                        let px = x + s + (i as u32 * 6 + c as u32) * s + dx;
                        let py = y + s + r as u32 * s + dy;
                        if px < img.width() && py < img.height() {
                            img.put_pixel(px, py, image::Rgb([255, 255, 255]));
                        }
                    }
                }
            }
        }
    }
}
