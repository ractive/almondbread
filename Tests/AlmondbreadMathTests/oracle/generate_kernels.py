#!/usr/bin/env python3
"""Generates Sources/AlmondbreadMath/FixedKernels.swift: straight-line short products
(columns n-2 ... 2n-2, see mulColumns/sqrColumns in Limbs.swift) for 3...8 limbs.

Fully unrolled code removes the per-column loop exits that dominate the looped Comba at these
sizes (measured on M1 Pro: 8-limb short square 29 ns -> 16 ns, short multiply 38 -> 32 ns).
Above 8 limbs the operands no longer fit in registers and the loops win.

Run: python3 generate_kernels.py > ../../../Sources/AlmondbreadMath/FixedKernels.swift
"""

MAX_N = 8
ACC = "(lo0, o) = lo0.addingReportingOverflow(l); lo1 &+= o ? 1 : 0; (hi0, o) = hi0.addingReportingOverflow(h); hi1 &+= o ? 1 : 0"


def gen_mul(n):
    k0 = n - 2
    out = [f"@inline(__always) @usableFromInline",
           f"func mulShort{n}(_ r: Limbs, _ a: Limbs, _ b: Limbs) {{"]
    out += [f"    let a{i} = a[{i}], b{i} = b[{i}]" for i in range(n)]
    out.append("    var cin0: UInt64 = 0, cin1: UInt64 = 0")
    out.append("    var lo0: UInt64, lo1: UInt64, hi0: UInt64, hi1: UInt64, h: UInt64, l: UInt64, o: Bool")
    for k in range(k0, 2 * n - 1):
        out.append("    lo0 = cin0; lo1 = cin1; hi0 = 0; hi1 = 0")
        for i in range(max(0, k - n + 1), min(k, n - 1) + 1):
            out.append(f"    (h, l) = a{i}.multipliedFullWidth(by: b{k - i}); {ACC}")
        out.append(f"    r[{k}] = lo0; (cin0, o) = lo1.addingReportingOverflow(hi0); cin1 = hi1 &+ (o ? 1 : 0)")
    out.append(f"    r[{2 * n - 1}] = cin0")
    out.append("}")
    return "\n".join(out)


def gen_sqr(n):
    k0 = n - 2
    out = [f"@inline(__always) @usableFromInline",
           f"func sqrShort{n}(_ r: Limbs, _ a: Limbs) {{"]
    out += [f"    let a{i} = a[{i}]" for i in range(n)]
    out.append("    var cin0: UInt64 = 0, cin1: UInt64 = 0")
    out.append("    var lo0: UInt64, lo1: UInt64, hi0: UInt64, hi1: UInt64, h: UInt64, l: UInt64, o: Bool")
    for k in range(k0, 2 * n - 1):
        out.append("    lo0 = 0; lo1 = 0; hi0 = 0; hi1 = 0")
        pairs = [(i, k - i) for i in range(max(0, k - n + 1), min(k, n - 1) + 1) if i < k - i]
        for i, j in pairs:
            out.append(f"    (h, l) = a{i}.multipliedFullWidth(by: a{j}); {ACC}")
        if pairs:
            out.append("    lo1 = (lo1 &<< 1) | (lo0 &>> 63); lo0 = lo0 &<< 1; hi1 = (hi1 &<< 1) | (hi0 &>> 63); hi0 = hi0 &<< 1")
        if k % 2 == 0 and k // 2 < n:
            i = k // 2
            out.append(f"    (h, l) = a{i}.multipliedFullWidth(by: a{i}); {ACC}")
        out.append("    (lo0, o) = lo0.addingReportingOverflow(cin0); lo1 = lo1 &+ cin1 &+ (o ? 1 : 0)")
        out.append(f"    r[{k}] = lo0; (cin0, o) = lo1.addingReportingOverflow(hi0); cin1 = hi1 &+ (o ? 1 : 0)")
    out.append(f"    r[{2 * n - 1}] = cin0")
    out.append("}")
    return "\n".join(out)


def main():
    print("// GENERATED by Tests/AlmondbreadMathTests/oracle/generate_kernels.py. Do not edit.")
    print("//")
    print("// Straight-line short products for 3...8 limbs: limbs n-2 ..< 2n of the product without the")
    print("// carries of the skipped low columns (exactly what mulColumns/sqrColumns(k0: n-2) write).")
    print()
    print("/// Short product a*b at limbs n-2..<2n via the unrolled kernel; false if n has none.")
    print("@inline(__always) @usableFromInline")
    print("func mulShortFixed(_ r: Limbs, _ a: Limbs, _ b: Limbs, _ n: Int) -> Bool {")
    print("    switch n {")
    for n in range(3, MAX_N + 1):
        print(f"    case {n}: mulShort{n}(r, a, b); return true")
    print("    default: return false")
    print("    }")
    print("}")
    print()
    print("/// Short square a*a at limbs n-2..<2n via the unrolled kernel; false if n has none.")
    print("@inline(__always) @usableFromInline")
    print("func sqrShortFixed(_ r: Limbs, _ a: Limbs, _ n: Int) -> Bool {")
    print("    switch n {")
    for n in range(3, MAX_N + 1):
        print(f"    case {n}: sqrShort{n}(r, a); return true")
    print("    default: return false")
    print("    }")
    print("}")
    for n in range(3, MAX_N + 1):
        print()
        print(gen_mul(n))
        print()
        print(gen_sqr(n))


if __name__ == "__main__":
    main()
