#!/bin/sh
# Draft App Store screenshots from captured PNGs (scripts/ui-screenshots.sh / `--ui-demo=<scene>`
# windows on the Mac, `make ios-uitest TESTS=AppStoreShotsUITests` on the simulators): each one
# composed at an exact App Store size with a short caption above it (scripts/appstore-caption.swift),
# plus an uncaptioned copy filled to the same size, and an index.md listing files and captions.
#
# Usage: scripts/appstore-shots.sh manifest.tsv out-dir [notes.md]
# manifest.tsv: one shot per line, tab-separated: platform  source.png  name  caption
#   platform: mac (2880x1800) | iphone (1320x2868, 6.9") | ipad (2064x2752, 13")
#   lines starting with # are skipped. Writes out-dir/<platform>/<name>.png and <name>-raw.png.
set -e
cd "$(dirname "$0")/.."
MANIFEST=$1
OUT=$2
[ -n "$MANIFEST" ] && [ -n "$OUT" ] || { echo "usage: $0 manifest.tsv out-dir"; exit 2; }
COMPOSER=$(mktemp -d)/appstore-caption
swiftc -O -o "$COMPOSER" scripts/appstore-caption.swift
mkdir -p "$OUT"
INDEX=$OUT/index.md
{
    echo "# App Store screenshot drafts"
    echo
    echo "Generated by scripts/appstore-shots.sh on $(date '+%Y-%m-%d %H:%M'). Each shot: \`<name>.png\`"
    echo "(captioned) and \`<name>-raw.png\` (the capture alone at the same size: filled when its shape is"
    echo "within 3 %, otherwise fitted on black)."
} > "$INDEX"
last=""
TAB=$(printf '\t')
while IFS="$TAB" read -r platform src name caption; do
    case $platform in ''|\#*) continue ;; esac
    case $platform in
        mac) size="2880 1800"; label="Mac (2880x1800)" ;;
        iphone) size="1320 2868"; label="iPhone 6.9\" (1320x2868)" ;;
        ipad) size="2064 2752"; label="iPad 13\" (2064x2752)" ;;
        *) echo "unknown platform $platform"; exit 1 ;;
    esac
    mkdir -p "$OUT/$platform"
    # shellcheck disable=SC2086
    "$COMPOSER" "$src" "$OUT/$platform/$name.png" $size "$caption"
    # shellcheck disable=SC2086
    "$COMPOSER" "$src" "$OUT/$platform/$name-raw.png" $size ""
    if [ "$platform" != "$last" ]; then
        printf '\n## %s\n\n| File | Caption | Source |\n|---|---|---|\n' "$label" >> "$INDEX"
        last=$platform
    fi
    printf '| %s/%s.png | %s | %s |\n' "$platform" "$name" "$caption" "$(basename "$src")" >> "$INDEX"
    echo "$platform/$name.png"
done < "$MANIFEST"
# Optional notes appended to the index (what the drafts still lack, sources, ...).
if [ -n "$3" ]; then
    echo >> "$INDEX"
    cat "$3" >> "$INDEX"
fi
